import { PrismaClient } from "@prisma/client";
import bcrypt from "bcryptjs";

const prisma = new PrismaClient();

async function main() {
  const adminEmail = process.env.INITIAL_ADMIN_EMAIL?.toLowerCase().trim();
  const adminPassword = process.env.INITIAL_ADMIN_PASSWORD;

  if (!adminEmail || !adminPassword) {
    console.log("No INITIAL_ADMIN_EMAIL and INITIAL_ADMIN_PASSWORD provided. Skipping admin seed.");
    return;
  }

  const adminName = process.env.INITIAL_ADMIN_NAME?.trim() || "Kamil Tonkowicz";
  const passwordHash = await bcrypt.hash(adminPassword, 10);
  const existingAdmin = await prisma.user.findUnique({ where: { email: adminEmail } });
  const shouldUpdateName =
    !existingAdmin ||
    existingAdmin.name === "Administrator Izzy Lease" ||
    Boolean(process.env.INITIAL_ADMIN_NAME?.trim());

  const admin = await prisma.user.upsert({
    where: { email: adminEmail },
    update: {
      passwordHash,
      role: "ADMIN",
      ...(shouldUpdateName ? { name: adminName } : {}),
    },
    create: {
      email: adminEmail,
      name: adminName,
      passwordHash,
      role: "ADMIN",
    },
  });

  console.log(`Initial admin user successfully configured for: ${admin.email}`);

  // Seed default Organization: Izzy Lease Sp. z o.o.
  const defaultOrg = await prisma.organization.upsert({
    where: { nip: "6871964402" },
    update: {
      name: "Izzy Lease Sp. z o.o.",
      street: "ul. Domaniewska 37",
      postalCode: "02-672",
      city: "Warszawa",
      country: "PL",
      billingEmail: "kontakt@izzylease.pl",
      isActive: true,
    },
    create: {
      name: "Izzy Lease Sp. z o.o.",
      nip: "6871964402",
      street: "ul. Domaniewska 37",
      postalCode: "02-672",
      city: "Warszawa",
      country: "PL",
      billingEmail: "kontakt@izzylease.pl",
      isActive: true,
      billingMode: "UNLIMITED",
    },
  });

  console.log(`Default organization configured: ${defaultOrg.name} (NIP: ${defaultOrg.nip})`);

  // Invalidate cached PDF bytes generated by older PDF template versions so existing reports re-render with v0.3.0
  const invalidated = await prisma.report.updateMany({
    where: {
      pdfBytes: { not: null },
      OR: [
        { pdfGeneratorVersion: null },
        { pdfGeneratorVersion: { not: "0.3.0" } },
      ],
    },
    data: {
      pdfBytes: null,
      pdfGeneratedAt: null,
      pdfGeneratorVersion: null,
    },
  });

  if (invalidated.count > 0) {
    console.log(`Invalidated ${invalidated.count} cached report PDF(s) from older generator versions.`);
  }
}

main()
  .catch((e) => {
    console.error("Seeding failed:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
